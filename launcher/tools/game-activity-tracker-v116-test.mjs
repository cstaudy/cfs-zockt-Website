import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {GameActivityTracker}=require('../src/game-activity-tracker.js');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'cfs-ga-'));
const file=path.join(dir,'game-activity.json');
const sent=[];
const tracker=new GameActivityTracker({filePath:file,submitter:async payload=>{sent.push(payload);return{ok:true}}});
let snap=tracker.configure({enabled:true,source:'launcher_manual',gameName:'Warzone',platform:'playstation_5'});
assert.equal(snap.enabled,true);assert.equal(snap.active.game_name,'Warzone');assert.match(snap.presence_transition_id,/^cfsgp_[a-f0-9]{32}$/);
tracker.state.active.started_at=new Date(Date.now()-65_000).toISOString();tracker.state.active.last_seen_at=new Date().toISOString();tracker.persist();
tracker.configure({enabled:false,source:'launcher_manual',gameName:'Warzone',platform:'playstation_5'});
assert.equal(tracker.snapshot().active,null);assert.equal(tracker.snapshot().pending,1);
await tracker.flush({force:true});assert.equal(sent.length,1);assert.match(sent[0].client_event_id,/^cfsga_[a-f0-9]{32}$/);assert.equal(sent[0].platform,'playstation_5');
tracker.configure({enabled:true,source:'stream_capture',gameName:'Game.exe',platform:'unknown'});assert.equal(tracker.snapshot().active.platform,'pc');
tracker.stop('privacy_clear');assert.equal(tracker.snapshot().pending,0);assert.equal(tracker.snapshot().active,null);
console.log(JSON.stringify({ok:true,checks:10,areas:['opt_in','stable_ids','queue','flush','presence','privacy_clear']}));
