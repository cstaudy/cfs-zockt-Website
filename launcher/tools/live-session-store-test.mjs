import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
const require=createRequire(import.meta.url);
const {LiveSessionStore}=require("../src/live-session-store.js");
const dir=fs.mkdtempSync(path.join(os.tmpdir(),"cfs-live-marker-"));
const file=path.join(dir,"session","live-session.json");
const store=new LiveSessionStore(file,{warn(){}});
const id="11111111-1111-4111-8111-111111111111";
store.setActive({sessionId:id,provider:"mock",username:"creator",startedAt:"2026-09-07T10:00:00.000Z"});
let state=store.read();
if(!state.active||state.sessionId!==id||state.provider!=="mock")throw new Error("marker write/read failed");
store.markError(new Error("synthetic recovery block"));
state=store.read();
if(!state.active||!state.lastError.includes("synthetic"))throw new Error("marker was destroyed on recovery error");
store.clear();
if(store.read().active)throw new Error("marker clear failed");
console.log(JSON.stringify({ok:true,atomic:true,retained_on_error:true,cleared:true}));
