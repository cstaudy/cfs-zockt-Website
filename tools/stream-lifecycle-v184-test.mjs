import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const server=read('server.js'),js=read('public/assets/js/stream-studio.js'),html=read('public/pages/stream-studio.html'),pkg=JSON.parse(read('package.json')),sys=read('public/assets/js/page-system-check.js');
let n=0,ok=0;const check=(name,cond)=>{n++;if(cond){ok++;console.log(`PASS ${name}`)}else{console.error(`FAIL ${name}`);process.exitCode=1}};
check('Backend 3.20.29',pkg.version==='3.20.29'&&server.includes('3.20.29')&&sys.includes('3.20.29'));
check('Schema remains 78',sys.includes('schema:78'));
for(const status of ['starting','live','brb','ending','offline']) check(`Lifecycle UI ${status}`,html.includes(`data-lifecycle-scene="${status}"`)&&html.includes(`data-lifecycle-go="${status}"`));
check('Lifecycle enabled toggle',html.includes('id="streamLifecycleEnabled"'));
check('Lifecycle auto toggle',html.includes('id="streamLifecycleAuto"'));
check('Lifecycle dock registered server',server.includes('"preflight","lifecycle","session"'));
check('Lifecycle dock registered client',js.includes('"preflight","lifecycle","session"'));
check('Server config version 5',server.includes('version:5')&&server.includes('lifecycle:{enabled:false,auto_runtime:false'));
check('Client config version 5',js.includes('version:5')&&js.includes('lifecycle:{enabled:false,auto_runtime:false'));
for(const field of ['starting_scene_id','live_scene_id','brb_scene_id','ending_scene_id','offline_scene_id']) check(`Sanitizes ${field}`,server.includes(`${field}:safeScene(lifecycle.${field})`));
check('Manual lifecycle switch',js.includes('async function switchLifecycle(status'));
check('Runtime lifecycle mapper',js.includes('function runtimeLifecycleStatus(runtime)'));
check('Auto lifecycle only when enabled',js.includes('lc.enabled!==true||lc.auto_runtime!==true'));
check('Runtime poll applies lifecycle',js.includes('await applyRuntimeLifecycle()'));
check('Offline scene preset',js.includes('offline:{name:"Offline"'));
check('Published scenes only in selector',js.includes('filter(scene=>scene.status==="live")'));
check('Lifecycle switch requires source url',js.includes('if(!scene?.source_url)'));
check('No provider secrets in lifecycle',!html.includes('stream key')&&!html.includes('client_secret'));
console.log(`Stream Lifecycle v184: ${ok}/${n}`);if(ok!==n)process.exit(1);
