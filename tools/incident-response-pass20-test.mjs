import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const server=read('server.js');
const admin=read('public/assets/js/admin-creators.js');
const html=read('public/pages/admin-creators.html');
const app=read('public/assets/js/app.js');
const security=read('public/pages/security.html');
const pkg=JSON.parse(read('package.json'));
const policy=JSON.parse(read('ops/incident-response-policy.json'));
let pass=0,fail=0;
function check(name,ok){if(ok){pass++;console.log(`PASS ${name}`)}else{fail++;console.error(`FAIL ${name}`)}}
check('incident state table exists',server.includes('CREATE TABLE IF NOT EXISTS creator_incident_state'));
check('default website incident row exists',server.includes("VALUES('website','normal'"));
check('four incident modes are explicit',/normal","degraded","maintenance","security_lockdown/.test(server));
check('maintenance and lockdown are freeze modes',server.includes('INCIDENT_FREEZE_MODES = new Set(["maintenance","security_lockdown"])'));
check('public message is length limited',server.includes('INCIDENT_PUBLIC_MESSAGE_MAX = 240'));
check('public message strips control whitespace',server.includes('replace(/[\\r\\n\\t]+/g'));
check('write freeze sends Retry-After',server.includes('res.setHeader("Retry-After","300")'));
check('write freeze returns 503',server.includes('code:"incident_write_freeze"'));
check('incident state unavailable fails closed for writes',server.includes('code:"incident_state_unavailable"'));
check('admin routes exempt from write freeze',server.includes('path.startsWith("/api/admin/")'));
check('public support remains available',server.includes('path==="/api/public/security/csp-report"||path==="/api/public/support/report"'));
check('stripe webhook remains available',server.includes('path==="/api/billing/stripe/webhook"'));
check('admin/login access remains possible',server.includes('path==="/api/account/login"||path==="/api/account/logout"'));
check('account writes can be frozen',server.includes('path.startsWith("/api/account/")'));
check('creator writes can be frozen',server.includes('path.startsWith("/api/creator/")'));
check('billing writes can be frozen',server.includes('path.startsWith("/api/billing/")'));
check('review writes can be frozen',server.includes('path.startsWith("/api/public/reviews/")'));
check('TikTok auth is covered by freeze',server.includes('path.startsWith("/auth/tiktok")'));
check('public status reads incident state',server.includes('const incident=await getWebsiteIncidentState()'));
check('public status does not expose updated_by',!/return res\.json\(\{[\s\S]{0,350}updated_by/.test(server.slice(server.indexOf('"/api/public/status"'))));
check('admin incident GET exists',server.includes('"/api/admin/creator-suite/incident-state",requireCreatorAccount,requireCreatorAdmin'));
check('admin incident PUT exists',server.includes('app.put("/api/admin/creator-suite/incident-state"'));
check('security lockdown can revoke other sessions',server.includes('DELETE FROM creator_sessions WHERE token_hash<>$1'));
check('current admin session is preserved',server.includes('currentHash=currentCreatorSessionHash(req)'));
check('incident mode changes create security events',server.includes('"incident_mode_changed"'));
check('session revocation creates security event',server.includes('"incident_sessions_revoked"'));
check('admin incident panel exists',html.includes('id="adminIncidentPanel"'));
check('admin incident mode selector exists',html.includes('id="incidentMode"'));
check('admin public message is limited in UI',html.includes('id="incidentPublicMessage" maxlength="240"'));
check('admin explicit session revoke checkbox exists',html.includes('id="incidentRevokeSessions"'));
check('admin incident load uses admin API',admin.includes('loadIncidentState'));
check('admin incident save uses protected PUT',admin.includes('method:"PUT"')&&admin.includes('/api/admin/creator-suite/incident-state'));
check('lockdown requires public explanation in UI',admin.includes('Bitte für den Security Lockdown eine kurze öffentliche Meldung setzen.'));
check('homepage understands maintenance status',app.includes('maintenance: "WARTUNG AKTIV"'));
check('homepage understands security lockdown',app.includes('security_lockdown: "SICHERHEITS-MODUS AKTIV"'));
check('security page documents incident mode',security.includes('Incident- und Wartungsmodus'));
check('policy defines admin step-up',policy.operations?.admin_step_up_required===true);
check('policy defines admin audit',policy.operations?.admin_audit_required===true);
check('policy keeps support available',policy.always_available?.includes('/api/public/support/report'));
check('policy disables tracking fields',policy.privacy?.stores_raw_ip===false&&policy.privacy?.stores_user_agent===false&&policy.privacy?.stores_browser_fingerprint===false);
check('pass20 npm script is registered',pkg.scripts?.['incident20:check']==='node tools/incident-response-pass20-test.mjs .');
console.log(`\nIncident Response Pass 20: ${pass}/${pass+fail}`);
if(fail)process.exit(1);
