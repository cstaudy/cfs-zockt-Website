import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const json=rel=>JSON.parse(read(rel));
function assert(v,m){if(!v)throw new Error(m)}
const launcher=json('launcher/package.json');
const parts=String(launcher.version).split('.').map(Number);
assert(parts[0]>0||parts[1]>47||(parts[1]===47&&parts[2]>=19),`launcher must be >= 0.47.19, got ${launcher.version}`);
const server=read('server.js');
const bridge=read('launcher/src/bridge-client.js');
const main=read('launcher/main.js');
const controller=read('launcher/src/obs-websocket-controller.js');
const dashboard=read('public/pages/dashboard.html');
const dashboardJs=read('public/assets/js/page-dashboard.js');
const widgetHtml=read('public/pages/widget-studio.html');
const widgetJs=read('public/assets/js/widget-studio.js');
for(const needle of ['/api/creator/stream-ready','obsBridgeIntegrationState','/api/creator/widget-studio/widgets/:id/install-obs','obs_widget_install','/api/creator/widget-studio/obs-actions/:id'])assert(server.includes(needle),`server v142 contract missing: ${needle}`);
for(const needle of ['websocket_connected','current_scene','password_exposed:false'])assert(bridge.includes(needle),`bridge OBS health missing: ${needle}`);
assert(main.includes('executeObsWidgetInstallAction')&&main.includes('obsWebSocket.installBrowserSource'),'launcher action executor missing');
assert(main.includes('bridge.fetchLibrary()')&&main.includes('widget?.source_url'),'launcher must resolve private widget source URL from authenticated library');
assert(controller.includes('"CreateInput"')&&controller.includes('installBrowserSource'),'OBS CreateInput path missing');
assert(dashboard.includes('STREAM STARTCHECK')&&dashboard.includes('streamReadySteps'),'dashboard stream-ready UI missing');
assert(dashboardJs.includes('/api/creator/stream-ready')&&dashboardJs.includes('Dein Basis-Stream ist startklar'),'dashboard does not consume readiness endpoint');
assert(widgetHtml.includes('IN AKTUELLE OBS-SZENE EINFÜGEN'),'one-click OBS CTA missing');
assert(widgetJs.includes('installWidgetInObs')&&widgetJs.includes('/install-obs')&&widgetJs.includes('/obs-actions/'),'widget OBS install feedback path missing');
assert(!server.includes('obs_websocket_password'),'server must not persist OBS password');
const installRoute=server.slice(server.indexOf('app.post("/api/creator/widget-studio/widgets/:id/install-obs"'),server.indexOf('app.get("/api/creator/widget-studio/obs-actions/:id"'));
assert(installRoute&&!installRoute.includes('studioWidgetSourceUrl('),'OBS action queue must not materialize private widget source URL');
assert(!/payload\s*=\s*\{[^}]*\burl\s*:/s.test(installRoute),'OBS action queue must not persist widget URL/token');
assert(server.includes('roadmap:{')&&server.includes('multistream'), 'Creator Suite roadmap must continue beyond the OBS WebSocket foundation');
console.log(JSON.stringify({ok:true,launcher:launcher.version,stream_ready:true,one_click_obs_install:true,secret_policy:'launcher_local_only_and_no_widget_token_in_action_queue'}));
