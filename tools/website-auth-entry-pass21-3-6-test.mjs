import fs from "node:fs";
import path from "node:path";
const root = path.resolve(process.argv[2] || ".");
const read = p => fs.readFileSync(path.join(root,p),"utf8");
const checks=[];
const check=(name,ok)=>{checks.push([name,Boolean(ok)]);console.log(`${ok?"PASS":"FAIL"} ${name}`);};
const login=read("public/pages/login.html");
const forgot=read("public/pages/forgot-password.html");
const reset=read("public/pages/reset-password.html");
const verify=read("public/pages/verify-email.html");
const loginJs=read("public/assets/js/page-login.js");
const css=read("public/assets/css/styles.css");
const authPages=[login,forgot,reset,verify];
check("auth pages use public shell", authPages.every(x=>x.includes('class="site-header brand-header public-site-header"')&&x.includes('class="footer brand-footer public-footer"')));
check("auth pages stay noindex", authPages.every(x=>x.includes('content="noindex,nofollow,noarchive"')));
check("login and register forms preserved", login.includes('id="loginForm"')&&login.includes('id="mfaLoginForm"')&&login.includes('id="regForm"'));
check("webauthn client preserved", login.includes('/assets/js/webauthn-browser.js'));
check("free start is explicit", login.includes('FREE Plan')&&login.includes('Keine Zahlungsdaten')&&login.includes('KEIN AUTO-UPGRADE'));
check("creator transition is explicit", login.includes('Account')&&login.includes('Dashboard')&&login.includes('Tools verbinden'));
check("login links recovery and verification", login.includes('/pages/forgot-password.html')&&login.includes('/pages/verify-email.html'));
check("forgot flow IDs preserved", forgot.includes('id="forgotPasswordForm"')&&forgot.includes('id="forgotPasswordBtn"')&&forgot.includes('id="mailUnavailableNote"'));
check("reset flow IDs preserved", reset.includes('id="resetPasswordForm"')&&reset.includes('id="resetPasswordBtn"')&&reset.includes('data-rule="length"')&&reset.includes('data-rule="match"'));
check("verification flow IDs preserved", verify.includes('id="verifyEmailMsg"')&&verify.includes('id="verifyResendForm"')&&verify.includes('id="verifyResendBtn"'));
check("registration anchor UX present", loginJs.includes('registrationAnchor')&&loginJs.includes('scrollIntoView'));
check("password reset success UX present", loginJs.includes('params.get("password") === "reset"'));
check("dashboard redirect preserved", (loginJs.match(/location\.replace\("\/pages\/dashboard\.html"\)/g)||[]).length>=2);
check("pass 21.3.6 styles present", css.includes('PASS 21.3.6')&&css.includes('.auth-entry-grid')&&css.includes('.auth-recovery-layout'));
const failed=checks.filter(([,ok])=>!ok);
console.log(`Website Auth Entry Pass 21.3.6: ${checks.length-failed.length}/${checks.length}`);
if(failed.length)process.exit(1);
