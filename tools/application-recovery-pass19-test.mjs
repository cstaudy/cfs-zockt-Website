import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const json=f=>JSON.parse(read(f));
const pkg=json('package.json');
const policy=json('ops/application-recovery-policy.json');
const wf=read('.github/workflows/production-recovery.yml');
const deploy=read('.github/workflows/production-deploy.yml');
const edge=read('tools/production-edge-check.mjs');
const snapshot=read('tools/release-state-snapshot.mjs');
const evidence=read('tools/application-recovery-evidence.mjs');
const doctor=read('tools/application-recovery-doctor.mjs');
const gitignore=read('.gitignore');
const runbook=read('PRODUCTION_GO_LIVE_RUNBOOK.md');
let pass=0,fail=0; const check=(label,ok)=>{console.log(`${ok?'PASS':'FAIL'}  ${label}`);ok?pass++:fail++};
check('application recovery policy exists',policy.schema===1&&policy.provider==='render');
check('canonical recovery origin pinned',policy.canonical_origin==='https://cfs-zockt.de');
check('database rollback explicitly separated',policy.rollback?.never_restore_database_as_part_of_app_rollback===true);
check('known-good commit required',policy.rollback?.require_known_good_commit===true);
check('manual confirmation required',policy.rollback?.require_manual_confirmation===true);
check('post-recovery canary required',policy.rollback?.require_canary_after_recovery===true);
check('post-recovery external gate required',policy.rollback?.require_external_edge_gate_after_recovery===true);
check('recovery evidence age policy exists',Number(policy.evidence?.max_age_days)>0);
check('release snapshot script wired',pkg.scripts?.['release:snapshot']==='node tools/release-state-snapshot.mjs .');
check('snapshot verification script wired',pkg.scripts?.['release:snapshot:verify']==='node tools/release-state-verify.mjs .');
check('recovery evidence script wired',pkg.scripts?.['apprecovery:evidence']==='node tools/application-recovery-evidence.mjs');
check('recovery doctor script wired',pkg.scripts?.['apprecovery:doctor']==='node tools/application-recovery-doctor.mjs .');
check('pass19 test script wired',String(pkg.scripts?.['apprecovery19:check']||'').includes('application-recovery-pass19-test.mjs')&&String(pkg.scripts?.['apprecovery19:check']||'').includes('application-recovery-evidence-test.mjs'));
check('recovery workflow manual only',wf.includes('workflow_dispatch:')&&!wf.includes('push:'));
check('workflow explicit confirmation phrase',wf.includes('RECOVER_PRODUCTION'));
check('workflow validates Git SHA',wf.includes("grep -Eq '^[0-9a-fA-F]{7,40}$'"));
check('workflow checks out exact target',wf.includes('ref: ${{ inputs.target_commit_sha }}'));
check('workflow verifies actual SHA',wf.includes('git rev-parse HEAD'));
check('workflow requires committed lockfiles',wf.includes('npm run lockfiles:check'));
check('workflow backend uses npm ci',wf.includes('npm ci --ignore-scripts --no-audit --no-fund'));
check('workflow validates target preflight',wf.includes('npm run release:preflight'));
check('workflow snapshots target state',wf.includes('recovery-target-snapshot.json'));
check('workflow requires canonical production target',wf.includes('https://cfs-zockt.de'));
check('workflow uses secret deploy hook',wf.includes('secrets.RENDER_DEPLOY_HOOK_URL'));
check('specific commit sent as deploy-hook ref',wf.includes("url.searchParams.set('ref',sha)"));
check('workflow waits for recovery canary',wf.includes('application-recovery-canary.json'));
check('workflow runs real edge gate',wf.includes('application-recovery-edge.json'));
check('workflow creates recovery evidence',wf.includes('application-recovery-evidence.json'));
check('workflow does not call database restore',!wf.includes('dbrestore:run')&&!wf.includes('database-restore.mjs'));
check('normal production deploy creates release snapshot',deploy.includes('Create release-state snapshot'));
check('normal deploy uploads release snapshot',deploy.includes('reports/release-state-snapshot.json'));
check('snapshot hashes critical files',snapshot.includes('critical_files')&&snapshot.includes("sha256(file)"));
check('snapshot records git SHA',snapshot.includes('git_sha:gitSha()'));
check('snapshot stores secret presence only',snapshot.includes('configured:Boolean(process.env[name])')&&snapshot.includes('No secret values are stored'));
check('snapshot never serializes process.env wholesale',!snapshot.includes('...process.env')&&!snapshot.includes('JSON.stringify(process.env'));
check('edge check supports JSON report',edge.includes("const report={schema:1")&&edge.includes("fs.writeFileSync(outPath"));
check('recovery evidence requires successful canary',evidence.includes('canary.ok!==true'));
check('recovery evidence requires successful edge gate',evidence.includes('edge.ok!==true'));
check('recovery evidence hashes input evidence',evidence.includes('canary_evidence_sha256')&&evidence.includes('edge_evidence_sha256'));
check('recovery evidence records no database rollback',evidence.includes('Database recovery is a separate procedure'));
check('doctor checks lockfiles',doctor.includes('Root lockfile vorhanden')&&doctor.includes('Launcher lockfile vorhanden'));
check('doctor checks deploy hook presence only',doctor.includes('Render Deploy Hook konfiguriert')&&doctor.includes('secret presence only'));
check('doctor checks recovery evidence',doctor.includes('Application-Recovery-Evidence vorhanden'));
check('recovery evidence is gitignored',gitignore.includes('reports/application-recovery-evidence.json'));
check('release snapshot is gitignored',gitignore.includes('reports/release-state-snapshot.json'));
check('runbook documents application rollback gate',runbook.includes('Application Rollback / Recovery')||runbook.includes('Application-Recovery'));
console.log(`\nApplication Recovery Pass 19: ${pass}/${pass+fail}`); if(fail)process.exit(1);
