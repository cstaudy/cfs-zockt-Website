import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const {parseMonth,invoiceMoneyFromStripe,refundMoneyFromStripe,sumVerifiedStripeEvents}=require('../lib/admin-finance-v32071.js');
let n=0;function ok(f){f();n++}
const inv=(id,amt=1000)=>({type:'invoice.paid',data:{object:{object:'invoice',id,currency:'eur',amount_paid:amt}}});
const ref=(charge,amt=250,invoice='in_good')=>({type:'charge.refunded',data:{object:{object:'charge',id:charge,invoice,currency:'eur',amount_refunded:amt}}});
const event=(id,type,summary,livemode=true,outcome='processed')=>({event_id:id,event_type:type,summary,livemode,outcome,event_created:1790000000});
ok(()=>assert.equal(parseMonth('2026-12').until-parseMonth('2026-12').from,31*86400));
ok(()=>assert.equal(parseMonth('2027-02').until-parseMonth('2027-02').from,28*86400));
ok(()=>assert.throws(()=>parseMonth('2026-00'),RangeError));
ok(()=>assert.throws(()=>parseMonth('2026-13'),RangeError));
ok(()=>assert.deepEqual(invoiceMoneyFromStripe(inv('in_good')), {invoice_id:'in_good',currency:'eur',amount_paid_minor:1000}));
ok(()=>assert.equal(invoiceMoneyFromStripe(inv('in_bad',-1)),null));
ok(()=>assert.equal(invoiceMoneyFromStripe({...inv('in_good'),type:'invoice.created'}),null));
ok(()=>assert.equal(refundMoneyFromStripe(ref('ch_ok')).amount_refunded_minor,250));
ok(()=>assert.equal(refundMoneyFromStripe(ref('ch_ok',250,'wrong')),null));
const rows=[event('evt_1','invoice.paid',{finance_invoice:invoiceMoneyFromStripe(inv('in_good'))}),event('evt_2','invoice.paid',{finance_invoice:invoiceMoneyFromStripe(inv('in_good'))}),event('evt_3','invoice.paid',{finance_invoice:invoiceMoneyFromStripe(inv('in_test',999))},false),event('evt_4','charge.refunded',{finance_refund:refundMoneyFromStripe(ref('ch_ok',250))}),event('evt_5','charge.refunded',{finance_refund:refundMoneyFromStripe(ref('ch_ok',400))}),event('evt_6','charge.refunded',{finance_refund:refundMoneyFromStripe(ref('ch_other',500,'in_else'))})];
ok(()=>assert.equal(sumVerifiedStripeEvents(rows).invoice_count,1));
ok(()=>assert.deepEqual(sumVerifiedStripeEvents(rows).currencies[0],{currency:'eur',gross_minor:1000,refund_minor:400,net_before_fees_minor:600,invoices:1,refund_events:1}));
ok(()=>assert.equal(sumVerifiedStripeEvents(rows).unlinked_refunds,1));
ok(()=>assert.equal(sumVerifiedStripeEvents(rows,{mode:'test'}).currencies[0].gross_minor,999));
ok(()=>assert.equal(sumVerifiedStripeEvents([event('evt_old','invoice.paid',{})]).missing_legacy_invoice_amount,1));
ok(()=>assert.equal(sumVerifiedStripeEvents([]).complete,false));
ok(()=>assert.equal(sumVerifiedStripeEvents([event('x','invoice.paid',{finance_invoice:invoiceMoneyFromStripe(inv('in_a'))},true,'failed')]).invoice_count,0));
ok(()=>assert.equal(sumVerifiedStripeEvents([event('x','invoice.paid',{finance_invoice:invoiceMoneyFromStripe(inv('in_a'))})],{truncated:true}).truncated,true));
const server=readFileSync(new URL('../server.js', import.meta.url),'utf8');
ok(()=>assert.match(server,/"\/api\/admin\/creator-suite\/finance-report",requireCreatorAccount,requireCreatorAdmin,requireCreatorAdminSensitiveRead/));
ok(()=>assert.match(server,/finance_invoice:invoiceMoneyFromStripe\(event\)/));
ok(()=>assert.match(server,/finance_refund=refundMoneyFromStripe\(event\)/));
const html=readFileSync(new URL('../public/pages/admin-creators.html', import.meta.url),'utf8');
ok(()=>assert.match(html,/id="adminFinancePanel"/));
ok(()=>assert.match(html,/id="financeReportWarning"/));
const js=readFileSync(new URL('../public/assets/js/admin-finance-v32071.js', import.meta.url),'utf8');
ok(()=>assert.match(js,/\/api\/admin\/creator-suite\/finance-report/));
ok(()=>assert.match(js,/textContent/));
console.log(`Finance/RC 3.20.71: ${n}/${n} PASS`);
