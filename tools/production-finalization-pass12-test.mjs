import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const pkg=JSON.parse(read('package.json'));
const deploy=read('.github/workflows/production-deploy.yml');
const verify=read('.github/workflows/production-verification.yml');
const launcher=read('.github/workflows/launcher-release.yml');
const lockwf=read('.github/workflows/dependency-lockfiles.yml');
const runbook=read('PRODUCTION_GO_LIVE_RUNBOOK.md');
let pass=0,fail=0;
function check(label,ok){console.log(`${ok?'PASS':'FAIL'}  ${label}`);ok?pass++:fail++}
check('production:gate script wired',pkg.scripts?.['production:gate']==='node tools/production-release-gate.mjs .');
check('production:external-gate script wired',pkg.scripts?.['production:external-gate']==='node tools/production-release-gate.mjs . --external-only');
check('lockfile generation script wired',pkg.scripts?.['lockfiles:generate']==='node tools/generate-lockfiles.mjs');
check('lockfile check script wired',pkg.scripts?.['lockfiles:check']==='node tools/dependency-lockfile-enforcement-test.mjs .');
check('deploy requires lockfile check',deploy.includes('npm run lockfiles:check'));
check('backend deploy uses npm ci',deploy.includes('npm ci --ignore-scripts --no-audit --no-fund'));
check('launcher deploy uses npm ci',launcher.includes('npm ci --ignore-scripts --no-audit --no-fund'));
check('production URL no longer optional',deploy.includes('CFS_PRODUCTION_URL repository variable is required for a production deploy.'));
check('production URL canonical policy',deploy.includes('https://cfs-zockt.de')&&verify.includes('https://cfs-zockt.de'));
check('deploy runs external security gate',deploy.includes('npm run production:external-gate'));
check('verification runs external security gate',verify.includes('npm run production:external-gate'));
check('manual lockfile workflow exists',lockwf.includes('Generate Dependency Lockfiles'));
check('lockfile workflow verifies npm ci',lockwf.includes('npm ci --ignore-scripts --no-audit --no-fund'));
check('runbook documents Render root A target',runbook.includes('216.24.57.1'));
check('runbook documents www CNAME',runbook.includes('www')&&runbook.includes('CNAME'));
check('runbook documents AAAA removal',runbook.includes('AAAA'));
check('runbook documents external gate',runbook.includes('production:external-gate'));
console.log(`\nProduction Finalization Pass 12: ${pass}/${pass+fail}`);
if(fail)process.exit(1);
