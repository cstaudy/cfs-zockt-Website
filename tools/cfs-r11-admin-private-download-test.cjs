"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),crypto=require("node:crypto");
const root=path.resolve(__dirname,"..");
const {ownerDesktopAccess}=require(path.join(root,"lib/admin-private-desktop"));
const acc={id:"owner-id-01",email:"cstaudygaming@googlemail.com",email_verified_at:"2026-10-09"};
const cfg={ownerEmail:"cstaudygaming@googlemail.com",ownerCreatorId:"owner-id-01"};
assert.equal(ownerDesktopAccess(acc,cfg).allowed,true);
assert.equal(ownerDesktopAccess({...acc,email:"other@example.com"},cfg).allowed,false);
assert.equal(ownerDesktopAccess({...acc,id:"another-id"},cfg).allowed,false);
assert.equal(ownerDesktopAccess({...acc,email_verified_at:null},cfg).allowed,false);
assert.equal(ownerDesktopAccess(acc,{ownerEmail:""}).allowed,false);
assert.equal(ownerDesktopAccess({...acc,email:"  CSTAUDYGAMING@GOOGLEMAIL.COM "},cfg).allowed,true);
const source=fs.readFileSync(path.join(root,"server.js"),"utf8");
assert.match(source,/app\.get\("\/api\/admin\/desktop\/download",requireCreatorAccount,requireCreatorAdmin,requireCreatorAdminSensitiveRead/);
assert.match(source,/app\.get\("\/api\/admin\/desktop\/availability",requireCreatorAccount,requireCreatorAdmin/);
assert.match(source,/const owner=adminDesktopOwnerCheck\(req\.creatorAccount\);/);
assert.match(source,/res\.set\("Content-Disposition",'attachment;/);
assert.match(source,/ADMIN_DESKTOP_ZIP_SHA256/);
const admin=fs.readFileSync(path.join(root,"public/pages/admin.html"),"utf8");
assert.match(admin,/id="adminPrivatePcDownload"/);
assert.match(admin,/cfs-admin-private-download-v32077\.js/);
const rel="private/admin-desktop/cfs_zockt-admin-pc.zip";
const bundle=fs.readFileSync(path.join(root,rel));
assert.ok(bundle.length>1000);
const check=crypto.createHash("sha256").update(bundle).digest("hex");
assert.ok(source.includes(check));
assert.ok(!rel.startsWith("public/"));
console.log("PASS: R11 owner-only admin PC route and bundle (14 assertions)");
