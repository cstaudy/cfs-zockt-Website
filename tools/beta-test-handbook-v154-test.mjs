import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root=path.resolve(process.argv[2]||'.');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const json=file=>JSON.parse(read(file));
const server=read('server.js');
const schema=read('lib/database-schema-contract.js');
const bridge=read('launcher/src/bridge-client.js');
const main=read('launcher/main.js');
const preload=read('launcher/preload.js');
const renderer=read('launcher/renderer/app.js');
const launcherHtml=read('launcher/renderer/index.html');
const launcherCss=read('launcher/renderer/styles.css');
const adminHtml=read('public/pages/admin-creators.html');
const adminJs=read('public/assets/js/admin-creators.js');
const adminCss=read('public/assets/css/admin-beta-handbook-v154.css');
const pkg=json('package.json');
const launcherPkg=json('launcher/package.json');

let pass=0,total=0;
const ok=(name,value)=>{total++;console.log(`${value?'PASS':'FAIL'} ${name}`);if(value)pass++;};
const hasAll=(text,parts)=>parts.every(part=>text.includes(part));
const versionAtLeast=(actual,minimum)=>{const a=String(actual||'').split('.').map(Number),m=String(minimum||'').split('.').map(Number);for(let i=0;i<3;i++){if((a[i]||0)>(m[i]||0))return true;if((a[i]||0)<(m[i]||0))return false;}return true;};

ok('backend >= 3.20.0',versionAtLeast(pkg.version,'3.20.0'));
ok('launcher >= 0.47.26',versionAtLeast(launcherPkg.version,'0.47.26'));
ok('schema generation >= 73',/DATABASE_SCHEMA_VERSION\s*=\s*(?:7[3-9]|[89]\d|\d{3,})/.test(schema));
ok('backend runtime version bumped',server.includes(`const BACKEND_VERSION =\n    "${pkg.version}"`));
ok('handbook result table exists',server.includes('CREATE TABLE IF NOT EXISTS creator_beta_handbook_results'));
ok('handbook table is creator scoped',server.includes('creator_id TEXT NOT NULL REFERENCES creator_accounts(id) ON DELETE CASCADE'));
ok('handbook result is restricted',server.includes("CHECK (result IN ('passed','failed','skipped'))"));
ok('handbook unique per creator and step',server.includes('PRIMARY KEY (creator_id, step_key)'));
ok('handbook session linkage is optional and safe',server.includes('session_id UUID REFERENCES creator_beta_sessions(id) ON DELETE SET NULL'));
ok('handbook indexes exist',hasAll(server,['idx_creator_beta_handbook_result','idx_creator_beta_handbook_session']));
ok('handbook has explicit result allowlist',server.includes('BETA_HANDBOOK_RESULTS=new Set(["passed","failed","skipped"])'));
ok('registration step exists',server.includes('key:"account.registration"'));
ok('login step exists',server.includes('key:"account.login"'));
ok('launcher step exists',server.includes('key:"launcher.link"'));
ok('TikTok step exists',server.includes('key:"provider.tiktok"'));
ok('Twitch step exists',server.includes('key:"provider.twitch"'));
ok('OBS step exists',server.includes('key:"obs.connection"'));
ok('Widget runtime step exists',server.includes('key:"widgets.runtime"'));
ok('Widget OBS step exists',server.includes('key:"widgets.obs"'));
ok('CFS Studio scene step exists',server.includes('key:"studio.scene"'));
ok('CFS Studio capture/audio step exists',server.includes('key:"studio.capture_audio"'));
ok('single streaming step exists',server.includes('key:"streaming.single"'));
ok('multistream/recovery step exists',server.includes('key:"streaming.multi_recovery"'));
ok('handbook bundle computes untested progress',hasAll(server,['function betaHandbookBundle','summary.untested','summary.complete=summary.untested===0']));
ok('bridge beta status returns handbook',server.includes('handbook:betaHandbookBundle(handbookRows.rows)'));
ok('handbook write endpoint exists',server.includes('"/api/bridge/beta/handbook/:stepKey"'));
ok('handbook write requires active beta',server.includes('await requireActiveBetaBridge(req.studioBridge)'));
ok('unknown handbook steps fail closed',server.includes('if(!BETA_HANDBOOK_KEYS.has(stepKey))return res.status(404)'));
ok('invalid handbook results fail closed',server.includes('if(!BETA_HANDBOOK_RESULTS.has(resultValue))return res.status(400)'));
ok('foreign session linkage is rejected',server.includes('Beta-Session gehört nicht zu diesem Creator.'));
ok('diagnostics are opt in only',server.includes('req.body?.include_diagnostics===true?sanitizeBetaDiagnostics'));
ok('comments are bounded',server.includes('betaText(req.body?.comment,2000,""'));
ok('handbook write response is no-store',/app\.put\("\/api\/bridge\/beta\/handbook\/:stepKey"[\s\S]{0,260}Cache-Control","no-store"/.test(server));
ok('admin beta center loads handbook results',server.includes('FROM creator_beta_handbook_results h JOIN creator_accounts c'));
ok('admin beta center exposes catalog and summary',server.includes('handbook:{version:1,catalog:BETA_HANDBOOK_STEPS,summary:handbookSummary,results:handbookRows}'));
ok('bridge client saves handbook via signed mutating request',bridge.includes('saveBetaHandbookStep(stepKey,payload={})')&&bridge.includes('method:"PUT"'));
ok('bridge advertises handbook capability',bridge.includes('beta_test_handbook_v1: true'));
ok('launcher sends current safe diagnostic snapshot only when requested',main.includes('include_diagnostics:input.includeDiagnostics===true')&&main.includes('diagnostics:d'));
ok('launcher links handbook result to active local session',main.includes('session_id:local.active?local.sessionId:null'));
ok('launcher IPC handler exists',main.includes('launcher:beta-handbook-step'));
ok('preload exposes handbook IPC',preload.includes('saveBetaHandbookStep: input => ipcRenderer.invoke("launcher:beta-handbook-step", input)'));
ok('launcher handbook panel exists',hasAll(launcherHtml,['INTEGRIERTES BETA-TEST-HANDBUCH','betaHandbookList','betaHandbookProgress']));
ok('launcher handbook action buttons are rendered',hasAll(renderer,['HAT GEKLAPPT','FUNKTIONIERT NICHT','ÜBERSPRINGEN']));
ok('launcher handbook includes optional safe diagnostics copy',launcherHtml.includes('Technische Diagnose ist pro Schritt freiwillig'));
ok('renderer displays all three requested outcomes',hasAll(renderer,['GEKLAPPT','FUNKTIONIERT NICHT','ÜBERSPRUNGEN']));
ok('renderer collects optional comment',renderer.includes('data-handbook-comment'));
ok('renderer collects optional diagnostics consent',renderer.includes('data-handbook-diagnostics'));
ok('renderer submits handbook result through preload',renderer.includes('window.CFSLauncher.saveBetaHandbookStep'));
ok('launcher handbook has dedicated styling',launcherCss.includes('V154 BETA TEST HANDBOOK'));
ok('admin page loads dedicated handbook stylesheet',adminHtml.includes('/assets/css/admin-beta-handbook-v154.css'));
ok('admin handbook result panel exists',hasAll(adminHtml,['BETA-TEST-HANDBUCH','betaHandbookAdminList','betaHandbookAdminSummary']));
ok('admin renders tester and test step',adminJs.includes('item.creator?.display_name')&&adminJs.includes('step.title||item.step_key'));
ok('admin renders status and comment',adminJs.includes('FUNKTIONIERT NICHT')&&adminJs.includes('item.comment'));
ok('admin renders sanitized technical fields',hasAll(adminJs,['d.launcher_version','d.platform','d.provider','d.bridge_connected','d.local_output_running','d.output_gate']));
ok('admin handbook styling exists',adminCss.includes('beta-handbook-admin-card'));
ok('v154 check script registered',Boolean(pkg.scripts['beta-handbook154:check']));
ok('v154 release script chains v153 and handbook gate',pkg.scripts['release:v154']==='npm run release:v153 && npm run beta-handbook154:check && npm run feature-freeze154:check');

console.log(`\nBeta Test Handbook v154: ${pass}/${total} ${pass===total?'PASS':'FAIL'}`);
if(pass!==total)process.exit(1);
