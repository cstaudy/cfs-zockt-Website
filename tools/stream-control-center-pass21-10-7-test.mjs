import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve(process.argv[2]||'.');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];
const check=(name,ok)=>{checks.push({name,ok:Boolean(ok)});console.log(`${ok?'PASS':'FAIL'}  ${name}`)};

const catalog=read('launcher/src/stream-provider-catalog.js');
const main=read('launcher/main.js');
const preload=read('launcher/preload.js');
const engine=read('launcher/src/stream-engine.js');
const renderer=read('launcher/renderer/app.js');
const launcherHtml=read('launcher/renderer/index.html');
const websiteJs=read('public/assets/js/stream-studio.js');
const websiteHtml=read('public/pages/stream-studio.html');
const pkg=JSON.parse(read('package.json'));

check('Provider-Katalog vorhanden',catalog.includes('providerCatalogPublic'));
check('YouTube als direkt unterstützt markiert',/youtube:[\s\S]*support:"supported"/.test(catalog));
check('Twitch als direkt unterstützt markiert',/twitch:[\s\S]*support:"supported"/.test(catalog));
check('TikTok als zugangsabhängig markiert',/tiktok:[\s\S]*support:"conditional"/.test(catalog));
check('TikTok-Hinweis umgeht keine Freigaben',catalog.includes('CFS umgeht keine TikTok-Zugriffsregeln'));
check('YouTube bevorzugt RTMPS',/youtube:[\s\S]*transport:"RTMPS"/.test(catalog));
check('Twitch RTMP-Ingest dokumentiert',catalog.includes('rtmp://<TWITCH-INGEST-SERVER>/app'));
check('Provider-Dokumentation nur per https',catalog.includes('https://support.google.com/youtube')&&catalog.includes('https://dev.twitch.tv'));
check('Provider-Metadaten im App-State',main.includes('streamProviders:providerCatalogPublic()'));
check('Lokaler Stream-Preflight vorhanden',main.includes('async function streamEnginePreflight()'));
check('Preflight prüft Bridge',main.includes('"Launcher Bridge"'));
check('Preflight prüft lokale Verschlüsselung',main.includes('"Lokaler Secret-Speicher"'));
check('Preflight prüft Plan-Limit',main.includes('"Plan-Limit"'));
check('Preflight prüft Credentials pro Ziel',main.includes('credential_${target.id}'));
check('Provider-Dokumente werden über Main-Prozess geöffnet',main.includes('openStreamProviderDocs')&&main.includes('shell.openExternal(url)'));
check('Provider-Dokument-URL kommt aus festem Katalog',main.includes('const info=streamProviderInfo(provider)'));
check('Preload exponiert Preflight',preload.includes('preflightStreamEngine'));
check('Preload exponiert Einzelziel Start/Stop',preload.includes('startStreamTarget')&&preload.includes('stopStreamTarget'));
check('Engine verwaltet manuell pausierte Ziele',engine.includes('this.pausedTargets=new Set()'));
check('Manuell gestopptes Ziel reconnectet nicht sofort',engine.includes('!this.pausedTargets.has(id)'));
check('Einzelziel Stop implementiert',engine.includes('async stopTarget(targetId)'));
check('Einzelziel Start implementiert',engine.includes('async startTarget(targetId)'));
check('Globaler Stop leert Pause-Zustand',engine.includes('this.pausedTargets.clear()'));
check('Launcher zeigt Provider-Support',renderer.includes('streamSupportLabel'));
check('Launcher zeigt provider-spezifische Hinweise',renderer.includes('stream-provider-hint'));
check('Launcher hat Preflight-UI',launcherHtml.includes('preflightStreamEngine')&&launcherHtml.includes('streamEnginePreflightResult'));
check('Launcher nennt Twitch/YouTube/TikTok Regeln',launcherHtml.includes('<strong>Twitch:</strong>')&&launcherHtml.includes('<strong>YouTube:</strong>')&&launcherHtml.includes('<strong>TikTok:</strong>'));
check('Runtime erlaubt Einzelziel Stop/Start',renderer.includes('data-stop-stream-target')&&renderer.includes('data-start-stream-target'));
check('Einzelziel Stop weist auf Isolation hin',renderer.includes('Andere Ziele laufen weiter'));
check('Website zeigt YouTube Direkt-Support',websiteHtml.includes('YOUTUBE')&&websiteHtml.includes('RTMPS + Stream-Key'));
check('Website zeigt Twitch Direkt-Support',websiteHtml.includes('TWITCH')&&websiteHtml.includes('RTMP-Ingest + Stream-Key'));
check('Website zeigt TikTok als zugangsabhängig',websiteHtml.includes('TIKTOK')&&websiteHtml.includes('ZUGANG ABHÄNGIG'));
check('Website erklärt TikTok Zugang im Ziel',websiteJs.includes('LIVE-ZUGANG ERFORDERLICH'));
check('Website speichert weiterhin keine Keys',websiteHtml.includes('Kein Stream-Key und keine RTMP-Zieladresse wird in der CFS Cloud gespeichert'));
check('Control-Center Check als npm Script registriert',Boolean(pkg.scripts?.['stream-control21:check']));
check('Provider Adapter Check wieder registriert',Boolean(pkg.scripts?.['provider-adapters21:check']));
check('Gesamtcheck enthält Provider + Control Center',String(pkg.scripts?.['stream-studio21:check']||'').includes('provider-adapters21:check')&&String(pkg.scripts?.['stream-studio21:check']||'').includes('stream-control21:check'));

const pass=checks.filter(x=>x.ok).length;
console.log(`\nStream Control Center Pass 21.10.7: ${pass}/${checks.length} PASS`);
if(pass!==checks.length)process.exit(1);
