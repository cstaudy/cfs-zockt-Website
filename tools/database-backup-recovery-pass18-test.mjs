import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=r=>fs.readFileSync(path.join(root,r),'utf8');
const pkg=JSON.parse(read('package.json'));
const lib=read('tools/database-backup-lib.mjs');
const backup=read('tools/database-backup.mjs');
const verify=read('tools/database-backup-verify.mjs');
const restore=read('tools/database-restore.mjs');
const doctor=read('tools/database-recovery-doctor.mjs');
const policy=JSON.parse(read('ops/database-recovery-policy.json'));
const ignore=read('.gitignore');
let pass=0,fail=0; const check=(label,ok)=>{console.log(`${ok?'PASS':'FAIL'}  ${label}`); ok?pass++:fail++;};
check('backup create script registered',pkg.scripts['dbbackup:create']==='node tools/database-backup.mjs');
check('backup verify script registered',pkg.scripts['dbbackup:verify']==='node tools/database-backup-verify.mjs');
check('restore script registered',pkg.scripts['dbrestore:run']==='node tools/database-restore.mjs');
check('recovery doctor registered',pkg.scripts['recovery:doctor']==='node tools/database-recovery-doctor.mjs .');
check('pass18 check registered',pkg.scripts['recovery18:check']==='node tools/database-backup-recovery-pass18-test.mjs . && node tools/database-backup-crypto-test.mjs');
check('backup artifacts ignored',ignore.includes('backups/')&&ignore.includes('*.cfsbackup')&&ignore.includes('backups/*.manifest.json'));
check('restore evidence ignored',ignore.includes('reports/database-recovery-evidence.json'));
check('policy prefers provider PITR',policy.production?.preferred_recovery==='provider_pitr');
check('policy requires pre-migration backup',policy.production?.require_pre_migration_backup===true);
check('policy requires offsite logical copy',policy.logical_backup?.require_offsite_copy===true);
check('policy requires separate restore target',policy.restore?.require_separate_target===true);
check('policy forbids primary overwrite by default',policy.restore?.never_overwrite_primary_by_default===true);
check('policy defines restore drill freshness',Number(policy.restore?.max_drill_age_days)>0);
check('backup secret minimum enforced',/CFS_BACKUP_ENCRYPTION_KEY[\s\S]{0,100}32 Zeichen/.test(lib));
check('AES-256-GCM used',lib.includes("createCipheriv('aes-256-gcm'")&&lib.includes("createDecipheriv('aes-256-gcm'"));
check('random salt and IV used',lib.includes('randomBytes(16)')&&lib.includes('randomBytes(12)'));
check('scrypt key derivation used',lib.includes('scryptSync')&&lib.includes('N:32768'));
check('HKDF separates encryption and manifest keys',lib.includes('backup encryption v1')&&lib.includes('backup manifest hmac v1'));
check('manifest HMAC present',lib.includes('manifest_hmac_sha256')&&lib.includes("createHmac('sha256'"));
check('manifest HMAC compared timing-safe',lib.includes('timingSafeEqual'));
check('plaintext SHA256 recorded',lib.includes('plaintext_sha256'));
check('ciphertext SHA256 recorded',lib.includes('ciphertext_sha256'));
check('database credentials not stored in source manifest',/source:\{host:p\.host,port:Number\(p\.port\),database:p\.database\}/.test(lib));
check('pg password passed via child env rather than backup CLI URL',lib.includes('PGPASSWORD')&&!backup.includes('DATABASE_URL]'));
check('pg_dump custom archive used',backup.includes("'--format=custom'"));
check('backup excludes owner and privileges',backup.includes("'--no-owner'")&&backup.includes("'--no-privileges'"));
check('plaintext temp dump removed in finally',/finally\{fs\.rmSync\(temp,\{force:true\}\);\}/.test(backup));
check('partial encrypted files removed on backup failure',backup.includes('fs.rmSync(cipherFile')&&backup.includes('fs.rmSync(manifestFile'));
check('encrypted archive written mode 0600',lib.includes("createWriteStream(cipherFile,{mode:0o600})"));
check('verify checks manifest HMAC',verify.includes('decryptAndVerify'));
check('verify requires pg_restore archive listing',verify.includes("'--list'"));
check('verify deletes decrypted temp file',verify.includes('fs.rmSync(tempFile,{force:true})'));
check('restore requires separate target URL',restore.includes('--target-url=')&&restore.includes('CFS_RESTORE_TARGET_URL'));
check('restore blocks backup source database',restore.includes('Restore in die im Backup vermerkte Quell-Datenbank ist gesperrt'));
check('restore blocks current DATABASE_URL',restore.includes('Restore in DATABASE_URL'));
check('restore requires empty target',restore.includes("pg_catalog.pg_tables")&&restore.includes('Zieldatenbank ist nicht leer'));
check('restore has dry-run default',restore.includes('DRY-RUN: kein Restore ausgeführt'));
check('restore requires explicit execute flag',restore.includes("process.argv.includes('--execute')"));
check('restore requires explicit confirmation phrase',restore.includes('CFS_RESTORE_CONFIRM')&&restore.includes('RESTORE_TO_EMPTY_DATABASE'));
check('restore does not use destructive clean flag',!restore.includes("'--clean'"));
check('restore does not recreate/drop database',!restore.includes("'--create'")&&!restore.includes('dropdb'));
check('restore uses no-owner/no-privileges',restore.includes("'--no-owner'")&&restore.includes("'--no-privileges'"));
check('restore writes recovery evidence after successful verification',restore.includes('database-recovery-evidence.json')&&restore.includes('restored_user_tables'));
check('doctor checks PostgreSQL client tools',doctor.includes("commandVersion('pg_dump')")&&doctor.includes("commandVersion('pg_restore')")&&doctor.includes("commandVersion('psql')"));
check('doctor checks backup secret without printing it',doctor.includes('CFS_BACKUP_ENCRYPTION_KEY')&&!doctor.includes('console.log(process.env.CFS_BACKUP_ENCRYPTION_KEY'));
check('doctor checks restore evidence freshness',doctor.includes('max_drill_age_days')&&doctor.includes('verified_at'));
console.log(`\nDatabase Backup / Recovery Pass 18: ${pass}/${pass+fail}`); if(fail)process.exit(1);
