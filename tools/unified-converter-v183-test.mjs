ok('One admin converter exists',admin.includes('id="adminUnifiedConverter"'));
ok('Admin copy says one converter',admin.includes('V183 · EIN UMWANDLER')&&admin.includes('Ein zentraler Produkt-Umwandler'));
ok('Legacy creator widget converter removed',!studio.includes('id="wsWidgetConverter"')&&!studio.includes('WIDGET-UMWANDLER'));
ok('Legacy creator panel converter removed',!studio.includes('id="wsPanelConverter"')&&!studio.includes('PANEL-UMWANDLER'));
