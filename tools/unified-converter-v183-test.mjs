for(const id of ['adminConverterType','adminConverterPlatform','adminConverterDetail','adminConverterOutput','adminConverterVariants','adminConverterPreset','adminConverterBranding','adminConverterTitle','adminConverterCollection','adminConverterGenerate'])ok(`Unified field ${id}`,admin.includes(`id="${id}"`));
