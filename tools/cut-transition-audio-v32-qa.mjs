import fs from "node:fs";import path from "node:path";
const root=path.resolve(process.argv[2]||path.join(import.meta.dirname,"..")),must=(v,m)=>{if(!v)throw new Error(m)};
const server=fs.readFileSync(path.join(root,"server.js"),"utf8");
const model=fs.readFileSync(path.join(root,"lib/creator-cut-studio.js"),"utf8");
const jobs=fs.readFileSync(path.join(root,"lib/creator-cut-jobs.js"),"utf8");
const html=fs.readFileSync(path.join(root,"public/pages/cut-studio.html"),"utf8");
const js=fs.readFileSync(path.join(root,"public/assets/js/cut-studio.js"),"utf8");
const engine=fs.readFileSync(path.join(root,"launcher/src/cut-media-engine.js"),"utf8");
const pkg=JSON.parse(fs.readFileSync(path.join(root,"launcher/package.json"),"utf8"));
for(const col of ["audio_gain_db","audio_fade_in_ms","audio_fade_out_ms"])must(server.includes(col),col);
must(model.includes("CUT_TRANSITIONS")&&model.includes("CUT_ENCODERS"),"transition/encoder model");
must((jobs.includes("schema:3")||jobs.includes("schema:4")||jobs.includes("schema:5")||jobs.includes("schema:6")||jobs.includes("schema:7"))&&jobs.includes("audio_normalize")&&jobs.includes("transition_ms"),"manifest schema 3+");
for(const id of ["cutTransition","cutTransitionMs","cutEncoder","cutAudioNormalize","cutAudioBitrate"])must(html.includes(`id="${id}"`),id);
must(js.includes("audio_gain_db")&&js.includes("audio_fade_in_ms")&&js.includes("audio_fade_out_ms"),"audio UI save");
must(engine.includes("xfade=transition=")&&engine.includes("acrossfade=d="),"transition engine");
must(engine.includes("loudnorm=I=-16")&&engine.includes("anullsrc=channel_layout=stereo"),"audio engine");
must(engine.includes("h264_nvenc")&&engine.includes("h264_qsv")&&engine.includes("h264_amf"),"gpu prep");
must((pkg.build?.extraResources||[]).some(x=>x.from==="vendor/ffmpeg"&&x.to==="ffmpeg"),"ffmpeg bundle config");
must(!server.includes("cut-studio/video-upload"),"cloud video upload must not exist");
console.log(JSON.stringify({ok:true,schema:"3+",transitions:true,audio:true,gpu_prep:true,ffmpeg_bundle_prep:true,no_cloud_video:true}));
