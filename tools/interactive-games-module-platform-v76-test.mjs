import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const root=process.argv[2]?path.resolve(process.argv[2]):process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const creatorGames=require(path.join(root,'lib/creator-games.js'));
const {InteractiveGameServiceManager}=require(path.join(root,'launcher/src/interactive-game-service-manager.js'));
const {BridgeClient}=require(path.join(root,'launcher/src/bridge-client.js'));
let pass=0; const check=(name,fn)=>{try{fn();pass++;console.log(`PASS ${name}`)}catch(e){console.error(`FAIL ${name}: ${e.message}`);process.exitCode=1}};
check('launcher version 0.47.7',()=>assert.equal(require(path.join(root,'launcher/package.json')).version,'0.47.7'));
check('dynamic local game key accepted',()=>assert.equal(creatorGames.sanitizeGameProfile({game_type:'local:my-game'}).game_type,'local:my-game'));
check('dynamic local game gets launcher engine',()=>assert.equal(creatorGames.gameDefinition('local:my-game').engine,'launcher_local'));
check('dynamic local terminal id derived safely',()=>assert.equal(creatorGames.gameDefinition('local:my-game').terminal_id,'my-game'));
check('invalid dynamic key fails closed to chat battle',()=>assert.equal(creatorGames.sanitizeGameProfile({game_type:'local:../bad'}).game_type,'chat_battle'));
const bundledRoot=path.join(root,'launcher/resources/interactive-games-terminal');
const manager=new InteractiveGameServiceManager({serviceRoot:bundledRoot,userDataPath:os.tmpdir(),port:8794});
check('bundled modules discovered without service start',()=>assert.ok(manager.catalogSnapshot().length>=4));
check('bundled module discovery includes nexus',()=>assert.ok(manager.catalogSnapshot().some(g=>g.id==='nexus')));
check('bundled module discovery includes boss arena',()=>assert.ok(manager.catalogSnapshot().some(g=>g.id==='boss-arena')));
check('module manifests are sanitized',()=>assert.ok(manager.catalogSnapshot().every(g=>/^[a-z0-9_-]{1,64}$/.test(g.id)&&Array.isArray(g.events))));
const bridge=new BridgeClient({settings:{backendUrl:'https://example.invalid'},token:'x',version:'0.47.7',interactiveGamesProvider:()=>manager.snapshot()});
check('bridge advertises catalog capability',()=>assert.equal(bridge.capabilities.interactive_games_catalog_v1,true));
check('bridge advertises sanitized modules',()=>assert.ok(Array.isArray(bridge.capabilities.interactive_game_modules)&&bridge.capabilities.interactive_game_modules.length>=4));
check('bridge does not expose game service token',()=>assert.equal(JSON.stringify(bridge.capabilities).includes(manager.token),false));
const server=read('server.js');
check('backend merges launcher module catalog',()=>assert.match(server,/gameCatalogForBridge/));
check('backend validates dynamic module installation',()=>assert.match(server,/interactive_game_module_missing/));
check('backend requires online catalog for new custom module selection',()=>assert.match(server,/interactive_game_catalog_offline/));
check('interactive action schema advanced to v2',()=>assert.match(server,/game_service_version:2/));
check('creator games api exposes service state',()=>assert.match(server,/service_ready:bridge\.capabilities\?\.interactive_games_service_ready/));
check('stream studio exposes game engine health',()=>assert.match(server,/interactive_game_engine:/));
const gamesJs=read('public/assets/js/games.js');
check('games UI preserves module metadata',()=>assert.match(gamesJs,/module_version:selected\.version/));
check('games UI shows module count',()=>assert.match(gamesJs,/moduleCount/));
const streamJs=read('public/assets/js/stream-studio.js');
check('stream UI shows local service readiness',()=>assert.match(streamJs,/SERVICE \$\{engine\.service_ready/));
const main=read('launcher/main.js');
check('launcher executes terminal id from signed action payload',()=>assert.match(main,/selectGame\(gameType,terminalId\)/));
check('launcher heartbeat gets interactive game snapshot provider',()=>assert.match(main,/interactiveGamesProvider:/));
check('launcher renderer exposes installed module count',()=>assert.match(read('launcher/renderer/app.js'),/installedModules\.length/));
console.log(`${pass}/24 PASS`);
if(pass!==24)process.exitCode=1;
