import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const root=path.resolve(process.argv[2]||'.'),require=createRequire(import.meta.url);
const ref=require(path.join(root,'lib/cut-reference-learning.js'));
const cut=require(path.join(root,'lib/creator-cut-studio.js'));
let pass=0;const check=(name,fn)=>{fn();pass++;console.log(`PASS ${name}`)};
check('six game profiles',()=>assert.equal(Object.keys(ref.GAME_PROFILES).length,6));
check('dbd profile exists',()=>assert(ref.GAME_PROFILES.dbd.categories.includes('mori')));
check('fps profile exists',()=>assert(ref.GAME_PROFILES.fps.categories.includes('clutch')));
check('battle royale profile exists',()=>assert(ref.GAME_PROFILES.battle_royale.categories.includes('win')));
check('sports profile exists',()=>assert(ref.GAME_PROFILES.sports_racing.categories.includes('goal')));
check('sandbox profile exists',()=>assert(ref.GAME_PROFILES.sandbox.categories.includes('build')));
check('youtube watch normalized',()=>assert.equal(ref.normalizePublicYoutubeUrl('https://youtube.com/watch?v=abcdefghijk'),'https://www.youtube.com/watch?v=abcdefghijk'));
check('youtube shorts normalized',()=>assert.equal(ref.normalizePublicYoutubeUrl('https://youtube.com/shorts/abcdefghijk'),'https://www.youtube.com/watch?v=abcdefghijk'));
check('non youtube blocked',()=>assert.throws(()=>ref.normalizePublicYoutubeUrl('https://example.com/x')));
const pending=ref.sanitizeReferenceSample({url:'https://youtu.be/abcdefghijk'},'dbd');
check('new reference stays pending',()=>assert.equal(pending.status,'pending'));
const analyzed={url:'https://youtu.be/abcdefghijk',status:'analyzed',referenceScore:82,hookSeconds:1.8,idealShortSeconds:31,actionDensity:.76,pacing:'fast',events:[{category:'chase',start:2,end:12,confidence:.9,shortScore:.8,hookScore:.8,reaction:.2,contextBefore:1.2,contextAfter:1.8,label:'Chase',reason:'visible'}],lessons:['Früher Hook']};
const profile=ref.aggregateReferenceProfile([pending,analyzed],'dbd');
check('pending samples excluded from aggregate',()=>assert.equal(profile.sample_count,1));
check('aggregate hook',()=>assert.equal(profile.hook_seconds,1.8));
check('aggregate pacing',()=>assert.equal(profile.pacing,'fast'));
check('aggregate category weight',()=>assert(profile.category_weights.chase>0));
check('wrong game category removed',()=>assert.equal(ref.sanitizeReferenceSample({...analyzed,events:[{...analyzed.events[0],category:'goal'}]},'dbd').events.length,0));
const learning=ref.sanitizeReferenceLearning({enabled:true,samples:[analyzed]},'dbd');
check('semantic separation forced',()=>assert.equal(learning.semantic_separation,true));
const noEvidence=ref.applyReferenceGuidance({score:.5,category:'chase',start:0,end:30,action_density:.7},learning,[]);
const evidence=ref.applyReferenceGuidance({score:.5,category:'chase',start:0,end:30,action_density:.7},learning,['chase']);
check('reference can add generic editorial boost',()=>assert(noEvidence.score>.5));
check('semantic category boost requires own evidence',()=>assert(evidence.score>noEvidence.score));
check('reference never creates category',()=>assert.equal(ref.applyReferenceGuidance({score:.5,start:0,end:30},learning,['chase']).category,undefined));
const sanitized=cut.sanitizeCutProject({title:'x',format:'vertical',export_preset:{game_profile:'fps',reference_learning:{enabled:true,samples:[{...analyzed,events:[{...analyzed.events[0],category:'clutch'}]}]}}});
check('project stores game profile',()=>assert.equal(sanitized.export_preset.game_profile,'fps'));
check('project stores learning safely',()=>assert.equal(sanitized.export_preset.reference_learning.semantic_separation,true));
check('unknown game profile falls back generic',()=>assert.equal(cut.sanitizeCutProject({export_preset:{game_profile:'nope'}}).export_preset.game_profile,'generic'));
const html=fs.readFileSync(path.join(root,'public/pages/cut-studio.html'),'utf8');
const js=fs.readFileSync(path.join(root,'public/assets/js/cut-studio.js'),'utf8');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const bridge=fs.readFileSync(path.join(root,'launcher/src/bridge-client.js'),'utf8');
check('ui has game profile selector',()=>assert.match(html,/id="cutGameProfile"/));
check('ui has reference toggle',()=>assert.match(html,/id="cutReferenceEnabled"/));
check('ui has reference urls',()=>assert.match(html,/id="cutReferenceUrls"/));
check('ui explains semantic separation',()=>assert.match(html,/niemals Beweis dafür/));
check('ui max eight references',()=>assert.match(html,/MAX\. 8/));
check('client only accepts youtube hosts',()=>assert.match(js,/youtube\.com/));
check('client preserves prior analyzed rows',()=>assert.match(js,/priorByUrl\.get\(url\)/));
check('project payload includes game profile',()=>assert.match(js,/game_profile:/));
check('project payload includes reference learning',()=>assert.match(js,/reference_learning:readReferenceLearning/));
check('bridge accepts sanitized analyzed reference only',()=>assert.match(server,/upsertAnalyzedReference/));
check('reference bridge route is creator scoped',()=>assert.match(server,/projects\/:id\/reference-learning/));
check('launcher bridge has provider-neutral submit method',()=>assert.match(bridge,/submitCutReferenceAnalysis/));
const merged=ref.upsertAnalyzedReference({enabled:true,samples:[pending]},analyzed,'dbd');
check('analyzed result replaces matching pending url',()=>assert.equal(merged.samples.filter(x=>x.url===pending.url).length,1));
check('merged analyzed result activates aggregate',()=>assert.equal(merged.aggregate.sample_count,1));
console.log(`CUT_STUDIO_REFERENCE_LEARNING_V47_PASS ${pass}/${pass}`);
