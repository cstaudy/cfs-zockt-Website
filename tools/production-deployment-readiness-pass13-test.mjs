import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
let passed=0,failed=0;
const test=(name,ok)=>{console.log(`${ok?'PASS':'FAIL'}  ${name}`);ok?passed++:failed++};
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const pkg=JSON.parse(read('package.json'));
const blueprint=read('render.blueprint.example.yaml');
const doctor=read('tools/production-setup-doctor.mjs');
const deploy=read('.github/workflows/production-deploy.yml');
const verify=read('.github/workflows/production-verification.yml');

test('Render Blueprint example exists',fs.existsSync(path.join(root,'render.blueprint.example.yaml')));
test('Blueprint uses Node runtime',/runtime:\s*node/.test(blueprint));
test('Blueprint auto deploy is off',/autoDeployTrigger:\s*["\']?off["\']?/.test(blueprint));
test('Blueprint build uses npm ci',/buildCommand:\s*npm ci\b/.test(blueprint));
test('Blueprint health check uses /api/health',/healthCheckPath:\s*\/api\/health/.test(blueprint));
test('Blueprint canonical domain is cfs-zockt.de',/domains:[\s\S]*-\s*cfs-zockt\.de/.test(blueprint));
test('Blueprint APP_BASE_URL is canonical',/APP_BASE_URL[\s\S]{0,100}https:\/\/cfs-zockt\.de/.test(blueprint));
test('Blueprint WebAuthn RP is canonical',/CFS_WEBAUTHN_RP_ID[\s\S]{0,100}cfs-zockt\.de/.test(blueprint));
test('Blueprint requires DB/TikTok/Launcher values via sync false', ['DATABASE_URL','TIKTOK_CLIENT_KEY','TIKTOK_CLIENT_SECRET','CFS_LAUNCHER_API_KEY'].every(k=>new RegExp(`key: ${k}\\n\\s+sync: false`).test(blueprint)));
test('Blueprint generates independent security secrets', ['CFS_TOKEN_ENCRYPTION_KEY','CFS_CSRF_SIGNING_SECRET','CFS_PUBLIC_REVIEW_HASH_SALT','CFS_PUBLIC_SUPPORT_HASH_SALT','CFS_MFA_RECOVERY_HASH_SALT'].every(k=>new RegExp(`key: ${k}\\n\\s+generateValue: true`).test(blueprint)));
test('Blueprint contains no obvious production secret literals',!/(sk_live_|whsec_|BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY)/.test(blueprint));
test('Production Setup Doctor exists',fs.existsSync(path.join(root,'tools/production-setup-doctor.mjs')));
test('Doctor validates lockfiles',doctor.includes("'package-lock.json'")&&doctor.includes("'launcher/package-lock.json'"));
test('Doctor validates canonical origin',doctor.includes("https://cfs-zockt.de"));
test('Doctor validates OAuth callback',doctor.includes('/auth/tiktok/callback'));
test('Doctor validates host allowlist',doctor.includes('CFS_ALLOWED_HOSTS'));
test('Doctor emits JSON report',doctor.includes('production-setup-doctor.json'));
test('package.json exposes deployment:doctor',pkg.scripts?.['deployment:doctor']==='node tools/production-setup-doctor.mjs .');
test('package.json exposes deployment13:check',pkg.scripts?.['deployment13:check']==='node tools/production-deployment-readiness-pass13-test.mjs .');
test('Production deploy still requires lockfiles',deploy.includes('npm run lockfiles:check'));
test('Production deploy still uses npm ci',deploy.includes('npm ci --ignore-scripts --no-audit --no-fund'));
test('Production verification still runs external gate',verify.includes('npm run production:external-gate'));
console.log(`\n${passed}/${passed+failed} production deployment readiness checks passed.`);
if(failed)process.exit(1);
