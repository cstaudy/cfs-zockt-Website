import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const root=path.resolve(process.argv[2]||'.');
let pass=0;
function check(name,fn){try{fn();pass++;console.log(`PASS ${name}`)}catch(error){console.error(`FAIL ${name}: ${error.message}`);process.exitCode=1}}
const portability=require(path.join(root,'lib/game-profile-portability.js'));
const games=require(path.join(root,'lib/creator-games.js'));
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const page=fs.readFileSync(path.join(root,'public/pages/games.html'),'utf8');
const js=fs.readFileSync(path.join(root,'public/assets/js/games.js'),'utf8');
const bridge=fs.readFileSync(path.join(root,'launcher/src/bridge-client.js'),'utf8');
const manager=fs.readFileSync(path.join(root,'launcher/src/interactive-game-service-manager.js'),'utf8');
const support=fs.readFileSync(path.join(root,'launcher/src/support-bundle.js'),'utf8');
const launcherPkg=require(path.join(root,'launcher/package.json'));
check('launcher version 0.47.7',()=>assert.equal(launcherPkg.version,'0.47.7'));
check('profile bundle schema fixed',()=>assert.equal(portability.PROFILE_BUNDLE_SCHEMA,1));
check('preset catalog includes core presets',()=>assert.ok(portability.publicGamePresets(games.publicGameCatalog()).length>=8));
check('dynamic local preset generated',()=>{const p=portability.publicGamePresets([...games.publicGameCatalog(),{key:'local:test-game',label:'Test Game',category:'Custom',engine:'launcher_local',terminal_id:'test-game',version:'2.0.0'}]);assert.ok(p.some(x=>x.game_type==='local:test-game'))});
check('export bundle excludes runtime token fields by construction',()=>{const b=portability.buildGameProfileBundle({profile:{title:'X',game_type:'chat_battle'},rules:[]});assert.equal(b.public_token,undefined);assert.equal(b.service_token,undefined);assert.equal(b.schema,'cfs.game-profile')});
check('bundle parser rejects wrong schema',()=>assert.throws(()=>portability.parseGameProfileBundle({schema:'other',version:1,profile:{}})));
check('bundle parser rejects oversized rule list',()=>assert.throws(()=>portability.parseGameProfileBundle({schema:'cfs.game-profile',version:1,profile:{},rules:Array(101).fill({})})));
check('server exposes presets endpoint',()=>assert.match(server,/\/api\/creator\/games\/presets/));
check('server exposes profile export',()=>assert.match(server,/\/api\/creator\/games\/profile\/export/));
check('server exposes profile import',()=>assert.match(server,/\/api\/creator\/games\/profile\/import/));
check('import blocks active runtime',()=>assert.match(server,/game_profile_runtime_active/));
check('import validates local launcher module',()=>assert.match(server,/interactive_game_module_missing/));
check('import replaces rules transactionally',()=>{assert.match(server,/BEGIN[\s\S]*DELETE FROM creator_game_rules[\s\S]*COMMIT/)});
check('profile toolkit visible in games UI',()=>assert.match(page,/PROFILE TOOLKIT/));
check('profile import file is JSON-only',()=>assert.match(page,/id="importGameProfileFile"[^>]*accept="application\/json,\.json"/));
check('client limits import file size',()=>assert.match(js,/128\*1024/));
check('client export uses JSON blob',()=>assert.match(js,/application\/json/));
check('OBS source metadata visible',()=>assert.match(page,/id="gameObsState"/));
check('launcher manager computes catalog hash',()=>assert.match(manager,/catalogHash\(\)/));
check('bridge sends catalog hash only as sha256',()=>assert.match(bridge,/interactive_games_catalog_hash/));
check('server publishes catalog hash to creator UI',()=>assert.match(server,/catalog_hash:\/\^\[a-f0-9\]\{64\}\$/));
check('support bundle includes sanitized game report',()=>assert.match(support,/interactive-games\.json/));
check('support game report marks secrets excluded',()=>assert.match(support,/secretsIncluded:false/));
check('support game report marks raw media excluded',()=>assert.match(support,/rawMediaIncluded:false/));
console.log(`Interactive Games Profile Platform v80: ${pass}/24 PASS`);
if(process.exitCode)process.exit(process.exitCode);
