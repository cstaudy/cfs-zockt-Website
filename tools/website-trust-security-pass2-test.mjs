import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve(process.argv[2]||'.');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const server=read('server.js');
const home=read('public/index.html');
const support=read('public/pages/support.html');
const security=read('public/pages/security.html');
const admin=read('public/pages/admin-creators.html');
const adminJs=read('public/assets/js/admin-creators.js');
const supportJs=read('public/assets/js/support.js');
const env=read('.env.example');
const pkg=JSON.parse(read('package.json'));

const checks=[];const check=(name,ok)=>checks.push({name,ok:Boolean(ok)});
check('Private public support endpoint exists',server.includes('"/api/public/support/report"'));
check('Public support writes require trusted same-origin source',server.includes('publicSupportReportLimiter')&&server.includes('requireTrustedPublicWrite'));
check('Support report limiter is narrow',server.includes('PUBLIC_SUPPORT_RATE_MAX =\n    5'));
check('Support abuse protection uses HMAC hash',server.includes('PUBLIC_SUPPORT_HASH_SALT')&&server.includes('publicSupportHash'));
check('Support table stores submitter hash not raw IP',server.includes('CREATE TABLE IF NOT EXISTS public_support_reports')&&server.includes('submitter_hash CHAR(64)')&&!server.match(/public_support_reports[\s\S]{0,1200}\bip_address\b/));
check('Submission idempotency uses unique hash',server.includes('submission_hash CHAR(64) NOT NULL UNIQUE')&&server.includes('ON CONFLICT(submission_hash) DO NOTHING'));
check('Public report has honeypot',server.includes('req.body?.website')&&support.includes('support-honeypot'));
check('Support input lengths are bounded',server.includes('publicSupportMessage(req.body?.message,4000)')&&server.includes('publicSupportText(req.body?.subject,140'));
check('Optional email is validated',server.includes('publicSupportEmail')&&server.includes('gültige E-Mail-Adresse'));
check('Admin support list is protected',server.includes('"/api/admin/creator-suite/support-reports"')&&server.includes('requireCreatorAdmin'));
check('Admin support mutation uses trusted write controls',server.includes('"/api/admin/creator-suite/support-reports/:id"')&&server.includes('requireTrustedPublicWrite'));
check('Support admin statuses are explicit',server.includes('new","reviewing","resolved","rejected'));
check('Support page explains private handling',support.includes('Deine Meldung erscheint nicht öffentlich')&&support.includes('PRIVAT'));
check('Support page warns against secrets',support.includes('Passwörter und Tokens nie mitsenden')&&support.includes('Recovery-Codes'));
check('Support page does not invent response SLA',support.includes('Keine Sofort-Antwort versprochen'));
check('Support page has optional contact email',support.includes('name="contact_email"')&&support.includes('optional'));
check('Support form script is external',support.includes('<script src="/assets/js/support.js"></script>')&&!/<script(?![^>]*src=)[^>]*>/i.test(support));
check('Support JS blocks obvious secret pastes client-side',supportJs.includes('access[_ -]?token')&&supportJs.includes('Bitte entferne Passwörter oder Tokens'));
check('Support JS posts same-origin JSON',supportJs.includes('fetch("/api/public/support/report"')&&supportJs.includes('credentials:"same-origin"'));
check('Homepage links private reporting path',home.includes('/pages/support.html#support-report')&&home.includes('PRIVATER MELDEWEG'));
check('Security page documents private reporting path',security.includes('Privater Security-Meldeweg')&&security.includes('/pages/support.html#support-report'));
check('Admin UI has support/security workspace',admin.includes('id="adminSupportPanel"')&&admin.includes('Support- & Security-Inbox'));
check('Admin UI surfaces critical-open KPI',admin.includes('id="kSupportCritical"')&&admin.includes('id="focusSupportReports"'));
check('Admin JS loads support reports',adminJs.includes('loadSupportReports')&&adminJs.includes('/api/admin/creator-suite/support-reports'));
check('Admin JS can move reports through workflow',adminJs.includes('moderateSupportReport')&&adminJs.includes('resolved'));
check('Separate support hash salt documented',env.includes('CFS_PUBLIC_SUPPORT_HASH_SALT='));
check('Production edge checker script is wired',pkg.scripts?.['edge:check']==='node tools/production-edge-check.mjs'&&fs.existsSync(path.join(root,'tools/production-edge-check.mjs')));
check('Backend version stays 3.12.0',pkg.version==='3.12.0');

const failed=checks.filter(x=>!x.ok);
for(const item of checks)console.log(`${item.ok?'PASS':'FAIL'}  ${item.name}`);
console.log(`\n${checks.length-failed.length}/${checks.length} trust/security pass 2 checks passed.`);
if(failed.length)process.exit(1);
